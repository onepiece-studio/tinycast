    private static let currencyCodes = Dictionary(
        uniqueKeysWithValues: CurrencyData.all.map { ($0.name, $0.code) })

    static func badge(_ text: String?) -> String? {
        guard let text else { return nil }
        if let resource = labels[text] { return String(localized: resource) }
        if let code = currencyCodes[text] {
            let language = Bundle.main.preferredLocalizations.first ?? "en"
            guard language != "en" else { return text }
            return Locale(identifier: language).localizedString(forCurrencyCode: code) ?? text
        }
        return text
    }
